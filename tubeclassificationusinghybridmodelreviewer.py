def annotate_bars(ax, fmt="{:.2f}", fontsize=7.5, color="#343A40", rotation=90):
    """Vertical, non-overlapping bar-value labels (avoids the crowded
    horizontal-label overlap seen with many bars per group)."""
    for container in ax.containers:
        try:
            labels = ax.bar_label(container, fmt=fmt, fontsize=fontsize, color=color,
                                   padding=3, rotation=rotation)
            if rotation:
                for lab in labels:
                    lab.set_va("bottom" if rotation == 90 else "center")
                    lab.set_ha("center")
        except Exception:
            pass
    top = ax.get_ylim()[1]
    ax.set_ylim(top=top * 1.18)

