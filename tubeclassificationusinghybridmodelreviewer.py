# ## 4. Handcrafted Features — Color, Texture, Quality

# %%
def color_features(img):
    feats = []
    for i in range(3):                       # RGB mean/std
        ch = img[:, :, i].astype(np.float32)
        feats += [ch.mean(), ch.std()]
    hsv = cv2.cvtColor(img, cv2.COLOR_RGB2HSV)
    for i in range(3):                        # HSV mean/std
        ch = hsv[:, :, i].astype(np.float32)
        feats += [ch.mean(), ch.std()]
    for i in range(3):                        # RGB 8-bin histograms
        hist = cv2.calcHist([img], [i], None, [8], [0, 256]).flatten()
        hist = hist / (hist.sum() + 1e-8)
        feats += hist.tolist()
    return np.array(feats)

def texture_features(gray):
    glcm = graycomatrix(gray, distances=[1, 2], angles=[0, np.pi/4, np.pi/2, 3*np.pi/4],
                         levels=256, symmetric=True, normed=True)
    props = ['contrast', 'dissimilarity', 'homogeneity', 'energy', 'correlation', 'ASM']
    feats = []
    for p in props:
        feats += graycoprops(glcm, p).flatten().tolist()
    lbp = local_binary_pattern(gray, P=8, R=1, method='uniform')
    hist, _ = np.histogram(lbp, bins=np.arange(0, 11), density=True)
    feats += hist.tolist()
    return np.array(feats)

def quality_features(gray):
    lap_var = cv2.Laplacian(gray, cv2.CV_64F).var()          # blur / sharpness proxy
    brightness = gray.mean()
    contrast = gray.std()
    entropy = shannon_entropy(gray)
    sobelx = cv2.Sobel(gray, cv2.CV_64F, 1, 0, ksize=3)
    sobely = cv2.Sobel(gray, cv2.CV_64F, 0, 1, ksize=3)
    sharpness = np.sqrt(sobelx**2 + sobely**2).mean()
    return np.array([lap_var, brightness, contrast, entropy, sharpness])

def extract_handcrafted(img):
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    return np.concatenate([color_features(img), texture_features(gray), quality_features(gray)])

