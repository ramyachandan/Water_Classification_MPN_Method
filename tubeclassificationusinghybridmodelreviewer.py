# ## 7. Regularized Autoencoder with Latent-Dimension Search → Latent Representation
# Trained **only on the training set** (scaler + autoencoder fit on Train, applied to
# Val/Test) to avoid leakage. Several candidate latent dimensions are tried and the
# one with the lowest **validation** reconstruction loss is kept.

# %%
INPUT_DIM_FUSED = FUSED_train.shape[1]
LATENT_DIMS = [32, 64, 128]
AE_EPOCHS   = 80
AE_BATCH    = 32
AE_PATIENCE = 12

def build_autoencoder(input_dim, latent_dim, l2_reg=1e-4):
    reg = l2(l2_reg)
    inp = layers.Input(shape=(input_dim,))
    # ── Encoder ──
    x = layers.Dense(512, activation='relu', kernel_regularizer=reg)(inp)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.4)(x)
    x = layers.Dense(256, activation='relu', kernel_regularizer=reg)(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.3)(x)
    encoded = layers.Dense(latent_dim, activation='relu',
                            kernel_regularizer=reg, name='latent')(x)
    # ── Decoder ──
    x = layers.Dense(256, activation='relu', kernel_regularizer=reg)(encoded)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.3)(x)
    x = layers.Dense(512, activation='relu', kernel_regularizer=reg)(x)
    x = layers.BatchNormalization()(x)
    decoded = layers.Dense(input_dim, activation='linear')(x)

    ae  = Model(inp, decoded, name=f'AE_{latent_dim}')
    enc = Model(inp, encoded, name=f'Enc_{latent_dim}')
    ae.compile(optimizer=Adam(5e-4), loss='mse')
    return ae, enc

def fit_best_ae(X_train_sc, X_val_sc):
    best_ld, best_vl = None, np.inf
    best_enc_w, best_ae_w = None, None
    histories = {}

    for ld in LATENT_DIMS:
        tf.keras.backend.clear_session()
        ae, enc = build_autoencoder(X_train_sc.shape[1], ld)
        es = callbacks.EarlyStopping(monitor='val_loss', patience=AE_PATIENCE,
                                      restore_best_weights=True, verbose=0)
        h = ae.fit(X_train_sc, X_train_sc,
                   validation_data=(X_val_sc, X_val_sc),
                   epochs=AE_EPOCHS, batch_size=AE_BATCH,
                   callbacks=[es], verbose=0)
        vl = min(h.history['val_loss'])
        histories[ld] = h.history
        print(f"  [AE] latent_dim={ld:>4d}  best val_loss={vl:.5f}")
        if vl < best_vl:
            best_vl = vl
            best_ld = ld
            best_enc_w = enc.get_weights()
            best_ae_w = ae.get_weights()

    tf.keras.backend.clear_session()
    best_ae, best_enc = build_autoencoder(X_train_sc.shape[1], best_ld)
    best_enc.set_weights(best_enc_w)
    best_ae.set_weights(best_ae_w)
    return best_enc, best_ae, best_ld, histories, best_vl

