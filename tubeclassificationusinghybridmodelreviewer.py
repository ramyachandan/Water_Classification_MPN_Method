# ## 6. Build & Cache Feature Sets (Handcrafted / ResNet / Fused) for Train, Val, Test

# %%
def build_feature_sets(paths, cache_name, batch_size=32):
    """
    Builds (or loads from cache) handcrafted / ResNet50V2 / fused features for a
    given split. The cache is keyed only by `cache_name` (e.g. "train"), so if the
    underlying image folder changes size between runs (files added/removed, a
    fresh dataset dropped in the same Drive path, etc.) a stale .npz from a
    previous run could silently be reused — its row count would then disagree
    with the current `paths` / `y_*` arrays and blow up downstream (e.g. boolean
    indexing against y_train in the AE diagnostics). To prevent that, the cache
    is only trusted if its row count matches len(paths); otherwise it is
    discarded and rebuilt from scratch.
    """
    cache_path = os.path.join(OUT_DIR, f"{cache_name}_features.npz")
    if os.path.exists(cache_path):
        d = np.load(cache_path)
        if len(d['hc']) == len(paths):
            return d['hc'], d['rn'], d['fused']
        # else: stale cache silently discarded and features are re-extracted
        # below (no message printed to keep the output screen clean; the
        # row-count safety check itself is still enforced).

    hc_list, rn_list = [], []
    for i in tqdm(range(0, len(paths), batch_size), desc=f"Extracting {cache_name}"):
        batch_paths = paths[i:i + batch_size]
        batch_imgs = [preprocess_image(p) for p in batch_paths]
        for img in batch_imgs:
            hc_list.append(extract_handcrafted(img))
        rn_list.append(extract_resnet_batch(batch_imgs))

    hc = np.vstack(hc_list)
    rn = np.vstack(rn_list)
    fused = np.hstack([hc, rn])
    np.savez_compressed(cache_path, hc=hc, rn=rn, fused=fused)
    return hc, rn, fused

