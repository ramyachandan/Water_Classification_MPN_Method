cv_rows, val_rows, test_rows = [], [], []
cv_foldwise_rows = []         # long format -> Ablation, Classifier, Fold, metric columns
cv_folds_store = {}           # (ablation, classifier) -> dict of fold-wise metric lists (kept for boxplots)
trained_models = {}           # (ablation, classifier) -> (clf, scaler)
predictions_store = {}        # (ablation, classifier) -> preds / probas on val & test

for ablation_name, (Xtr, Xva, Xte) in feature_sets.items():
    for clf_name in get_classifiers().keys():

        # (1) Stratified 5-Fold CV (nested with RandomizedSearchCV) — TRAIN ONLY
        cv_res = cross_validate_model(clf_name, Xtr, y_train, n_splits=5)
        fold_metrics = cv_res.pop("fold_metrics")
        cv_folds_store[(ablation_name, clf_name)] = fold_metrics
        cv_rows.append({"Ablation Study": ablation_name, "Classifier": clf_name, **cv_res})

        n_folds = len(fold_metrics["Accuracy"])
        for f in range(n_folds):
            cv_foldwise_rows.append({
                "Ablation Study": ablation_name,
                "Classifier": clf_name,
                "Fold": f + 1,
                "Accuracy": fold_metrics["Accuracy"][f],
                "Precision": fold_metrics["Precision"][f],
                "Recall": fold_metrics["Recall"][f],
                "F1": fold_metrics["F1"][f],
                "AUCROC": fold_metrics["AUCROC"][f],
                "Log Loss": fold_metrics["Log Loss"][f],
            })

        # (2) RandomizedSearchCV on full Train -> evaluate on Validation
        clf_v, scaler_v, val_metrics, val_pred, val_proba = train_and_evaluate(
            clf_name, Xtr, y_train, Xva, y_val)
        val_rows.append({"Ablation Study": ablation_name, "Classifier": clf_name,
                          **{k: v for k, v in val_metrics.items() if k != "Best Params"}})

        # (3) RandomizedSearchCV on full Train -> evaluate on Test
        clf_t, scaler_t, test_metrics, test_pred, test_proba = train_and_evaluate(
            clf_name, Xtr, y_train, Xte, y_test)
        test_rows.append({"Ablation Study": ablation_name, "Classifier": clf_name,
                           **{k: v for k, v in test_metrics.items() if k != "Best Params"}})

        trained_models[(ablation_name, clf_name)] = (clf_t, scaler_t)
        predictions_store[(ablation_name, clf_name)] = {
            "val_pred": val_pred, "val_proba": val_proba,
            "test_pred": test_pred, "test_proba": test_proba,
            "best_params": test_metrics["Best Params"],
        }

        print(f"[Done] {ablation_name:30s} | {clf_name:18s} | "
              f"CV Acc={cv_res['CV Acc']:.3f}±{cv_res['CV Acc Std']:.3f} | "
              f"Test Acc={test_metrics['Accuracy']:.3f} | "
              f"Train Time={test_metrics['Training Time (s)']:.2f}s | "
              f"Peak Mem={test_metrics['Peak Train Memory (MB)']:.1f}MB | "
              f"Model Size={test_metrics['Model Size (KB)']:.1f}KB | "
              f"BestParams={test_metrics['Best Params']}")

