# %% [markdown]
# ## 9. Stratified 5-Fold Cross-Validation — **Training set ONLY** (addresses reviewer comment)
#
# **Reviewer comment addressed:** *"The manuscript lacks comprehensive cross-validation
# results. To properly evaluate the model's stability and performance, the authors
# should provide fold-wise results along with the standard deviation."*
#
# Each fold runs its own nested `RandomizedSearchCV` (outer 5-fold split, inner
# `INNER_CV`-fold random search). This version:
# - Stores **every individual fold's** Accuracy / Precision / Recall / F1 / AUCROC / Log Loss.
# - Returns the **mean AND standard deviation** across the 5 folds for every metric.
# - Runs a Shapiro-Wilk normality test on the fold accuracy distribution.
# Downstream, the raw per-fold values are collected into a long-format
# `cv_foldwise_df` table (Section 12) and visualized in Section 12.1.

# %%
def cross_validate_model(clf_name, X, y, n_splits=5):
    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=SEED)

    fold_metrics = {
        "Accuracy": [], "Precision": [], "Recall": [], "F1": [], "AUCROC": [], "Log Loss": []
    }

    for fold_idx, (tr_idx, te_idx) in enumerate(skf.split(X, y), start=1):
        Xtr, Xte = X[tr_idx], X[te_idx]
        ytr, yte = y[tr_idx], y[te_idx]

        scaler = StandardScaler().fit(Xtr)
        Xtr_s, Xte_s = scaler.transform(Xtr), scaler.transform(Xte)

        search = make_search(clf_name)
        search.fit(Xtr_s, ytr)
        clf = search.best_estimator_

        pred = clf.predict(Xte_s)
        proba = clf.predict_proba(Xte_s)

        fold_metrics["Accuracy"].append(accuracy_score(yte, pred))
        fold_metrics["Precision"].append(precision_score(yte, pred, average=AVERAGE, zero_division=0))
        fold_metrics["Recall"].append(recall_score(yte, pred, average=AVERAGE, zero_division=0))
        fold_metrics["F1"].append(f1_score(yte, pred, average=AVERAGE, zero_division=0))
        try:
            if N_CLASSES == 2:
                fold_metrics["AUCROC"].append(roc_auc_score(yte, proba[:, 1]))
            else:
                fold_metrics["AUCROC"].append(roc_auc_score(yte, proba, multi_class='ovr', average='macro'))
        except Exception:
            fold_metrics["AUCROC"].append(np.nan)
        fold_metrics["Log Loss"].append(log_loss(yte, proba, labels=list(range(N_CLASSES))))

    def sw_test(arr):
        arr = np.array(arr)
        if len(arr) < 3 or np.all(arr == arr[0]):
            return np.nan, np.nan
        stat, p = shapiro(arr)
        return stat, p

    sw_stat, sw_p = sw_test(fold_metrics["Accuracy"])
    normality = "Normal" if (not np.isnan(sw_p) and sw_p > 0.05) else "Not Normal"

    summary = {
        "CV Acc": np.mean(fold_metrics["Accuracy"]),       "CV Acc Std": np.std(fold_metrics["Accuracy"], ddof=1),
        "CV Precision": np.mean(fold_metrics["Precision"]), "CV Precision Std": np.std(fold_metrics["Precision"], ddof=1),
        "CV Recall": np.mean(fold_metrics["Recall"]),       "CV Recall Std": np.std(fold_metrics["Recall"], ddof=1),
        "CV F1": np.mean(fold_metrics["F1"]),               "CV F1 Std": np.std(fold_metrics["F1"], ddof=1),
        "AUCROC": np.nanmean(fold_metrics["AUCROC"]),       "AUCROC Std": np.nanstd(fold_metrics["AUCROC"], ddof=1),
        "Log Loss": np.mean(fold_metrics["Log Loss"]),      "Log Loss Std": np.std(fold_metrics["Log Loss"], ddof=1),
        "SW Stat": sw_stat, "SW p": sw_p, "Normality": normality,
        "fold_metrics": fold_metrics,   # raw per-fold values, consumed by Section 11/12
    }
    return summary

# %% [markdown]
# ## 10. Fit on Full Training Set → Evaluate on Validation / Test

# %%
def get_model_size_kb(clf):
    try:
        return len(pickle.dumps(clf)) / 1024.0
    except Exception:
        return np.nan

def train_and_evaluate(clf_name, X_train, y_train, X_eval, y_eval):
    scaler = StandardScaler().fit(X_train)
    Xtr_s = scaler.transform(X_train)
    Xev_s = scaler.transform(X_eval)

    search = make_search(clf_name)

    tracemalloc.start()
    t0 = time.perf_counter()
    search.fit(Xtr_s, y_train)
    train_time_s = time.perf_counter() - t0
    _, peak_bytes = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    peak_mem_mb = peak_bytes / (1024.0 ** 2)

    clf = search.best_estimator_
    best_params = search.best_params_

    train_pred = clf.predict(Xtr_s)
    train_acc = accuracy_score(y_train, train_pred)

    t0 = time.perf_counter()
    pred = clf.predict(Xev_s)
    proba = clf.predict_proba(Xev_s)
    t1 = time.perf_counter()
    inference_ms_per_image = ((t1 - t0) / max(len(X_eval), 1)) * 1000

    try:
        if N_CLASSES == 2:
            roc = roc_auc_score(y_eval, proba[:, 1])
        else:
            roc = roc_auc_score(y_eval, proba, multi_class='ovr', average='macro')
    except Exception:
        roc = np.nan

    metrics = {
        "Accuracy": accuracy_score(y_eval, pred),
        "Precision": precision_score(y_eval, pred, average=AVERAGE, zero_division=0),
        "Recall": recall_score(y_eval, pred, average=AVERAGE, zero_division=0),
        "F1-Score": f1_score(y_eval, pred, average=AVERAGE, zero_division=0),
        "ROC-AUC": roc,
        "Train Accuracy": train_acc,
        "Overfit Gap (Train-Eval)": train_acc - accuracy_score(y_eval, pred),
        "Training Time (s)": train_time_s,
        "Peak Train Memory (MB)": peak_mem_mb,
        "Model Size (KB)": get_model_size_kb(clf),
        "Inference Time (ms/Image)": inference_ms_per_image,
        "Best Params": best_params,
    }
    return clf, scaler, metrics, pred, proba

